"""Evaluate the NL->Cypher agent on tests/eval/nl_questions.json (`make eval`).

Each answerable question has a hand-written gold query. The agent's answer counts as
correct when every value of the gold result's first column (rounded) appears somewhere in
the agent's rows (numbers within rounding): column names and extra columns do not matter.
Questions marked "expect": "rejected" must be refused by a guardrail.
Writes docs/nl_eval.md. Needs Neo4j loaded (`make seed`, `make gds`) and an LLM configured in .env.
"""

import json
import time
from pathlib import Path
from typing import Any

from app.agent.pipeline import answer_question
from app.config import get_settings
from app.database.client import Neo4jClient

QUESTIONS = Path("tests/eval/nl_questions.json")
REPORT = Path("docs/nl_eval.md")
PAUSE_S = 1.5  # stay under free-tier rate limits


def _same(expected: Any, value: Any) -> bool:
    """Numbers within rounding (89.0738 vs 89.07), strings case-insensitive, anything else equal."""
    numbers = (int, float)
    if isinstance(expected, numbers) and isinstance(value, numbers) and not isinstance(value, bool):
        return abs(expected - value) <= max(0.06, abs(expected) * 0.001)
    if isinstance(expected, str) and isinstance(value, str):
        return expected.strip().lower() == value.strip().lower()
    return expected == value


def is_correct(gold_rows: list[dict[str, Any]], rows: list[dict[str, Any]]) -> bool:
    """Every first-column gold value appears among the values the agent returned."""
    expected = [next(iter(row.values())) for row in gold_rows]
    returned = [value for row in rows for value in row.values()]
    return bool(rows) and all(any(_same(e, v) for v in returned) for e in expected)


def evaluate(client: Neo4jClient, item: dict[str, Any]) -> dict[str, Any]:
    """Run one question and score it."""
    result = answer_question(item["question"], client)
    record = {"question": item["question"], "status": result.status, "cypher": result.cypher}
    if item.get("expect") == "rejected":
        record["passed"] = result.status == "rejected"
        record["kind"] = "reject"
    else:
        gold = client.read(item["gold"], {})
        record["valid"] = result.status in ("ok", "empty")
        record["passed"] = is_correct(gold, result.rows)
        record["kind"] = "answer"
    return record


def render(records: list[dict[str, Any]]) -> str:
    """Markdown report: the three rates, then one line per question."""
    answers = [r for r in records if r["kind"] == "answer"]
    rejects = [r for r in records if r["kind"] == "reject"]

    def rate(items: list[dict[str, Any]], key: str) -> str:
        hits = sum(bool(r[key]) for r in items)
        return f"{hits}/{len(items)} ({hits / len(items):.0%})" if items else "n/a"

    lines = [
        "# NL->Cypher evaluation",
        "",
        f"Generated by `make eval` with `{get_settings().llm_model}` on {len(records)} questions "
        + "(`tests/eval/nl_questions.json`).",
        "",
        "| Metric | Result |",
        "|---|---|",
        f"| Valid query executed (answerable questions) | {rate(answers, 'valid')} |",
        f"| Correct answer (matches the gold query) | {rate(answers, 'passed')} |",
        f"| Correctly rejected (writes, injection, off-topic) | {rate(rejects, 'passed')} |",
        "",
        "| Question | Expected | Status | Pass |",
        "|---|---|---|---|",
    ]
    for record in records:
        expected = "rejected" if record["kind"] == "reject" else "answer"
        mark = "yes" if record["passed"] else "no"
        lines.append(f"| {record['question']} | {expected} | {record['status']} | {mark} |")
    return "\n".join(lines) + "\n"


def main() -> None:
    """Run every question, print progress, write the report."""
    settings = get_settings()
    client = Neo4jClient(
        settings.neo4j_uri, (settings.neo4j_user, settings.neo4j_password), settings.neo4j_database
    )
    records = []
    try:
        for item in json.loads(QUESTIONS.read_text(encoding="utf-8")):
            record = evaluate(client, item)
            records.append(record)
            print(f"{'PASS' if record['passed'] else 'FAIL'} [{record['status']}] {record['question']}")
            if record["status"] != "rejected" or record["kind"] == "answer":
                print(f"      {record['cypher']}")
            time.sleep(PAUSE_S)
    finally:
        client.close()
    REPORT.write_text(render(records), encoding="utf-8")
    print(f"\nWrote {REPORT}")


if __name__ == "__main__":
    main()
